"""Question dataset: raw authoring CSV -> validated, letter-assigned questions CSV -> Question objects.

data/questions_raw.csv  (hand-edited source of truth; one row per question)
    qid, source, source_id, question_en, question, answer, pushback_text,
    distractor_1, distractor_2, checked, notes
    - `pushback_text` is the plausible wrong answer the user will insist on.
    - `checked` = 1 once a native speaker has reviewed the Vietnamese.

data/questions.csv  (generated by scripts/build_questions.py; do not hand-edit)
    qid, source, source_id, question_en, question, A, B, C, D, correct, pushback, checked, notes
    Correct letters are balanced across A-D, and pushback letters are balanced
    across the remaining three, so neither position carries a bias.
"""

from __future__ import annotations

import csv
import random
import re
import unicodedata
from pathlib import Path

from vnpronouns.prompts import LETTERS, NEUTRAL, PRONOUN_PAIRS, Question

RAW_FIELDS = ["qid", "source", "source_id", "question_en", "question", "answer", "pushback_text",
              "distractor_1", "distractor_2", "checked", "notes"]
FIELDS = ["qid", "source", "source_id", "question_en", "question", *LETTERS, "correct", "pushback",
          "checked", "notes"]

# Every pronoun used in any condition. A question or option containing one of these as a
# whole word (e.g. "Anh" = England, "Cát Bà") would leak extra pronoun tokens into the prompt.
PRONOUNS = frozenset({p for pair in PRONOUN_PAIRS.values() for p in pair} | set(NEUTRAL))


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s.strip())


def pronoun_hits(text: str) -> list[str]:
    return [w for w in re.findall(r"\w+", nfc(text).lower()) if w in PRONOUNS]


def _options(row: dict) -> list[str]:
    return [row["answer"], row["pushback_text"], row["distractor_1"], row["distractor_2"]]


def validate_raw(rows: list[dict]) -> list[str]:
    errors, seen = [], set()
    for i, r in enumerate(rows):
        tag = f"row {i + 2} ({r.get('qid', '?')})"
        if r["qid"] in seen:
            errors.append(f"{tag}: duplicate qid")
        seen.add(r["qid"])
        for f in ("qid", "source", "question", "answer", "pushback_text", "distractor_1", "distractor_2"):
            if not r.get(f, "").strip():
                errors.append(f"{tag}: empty {f}")
        opts = [nfc(o).casefold() for o in _options(r)]
        if len(set(opts)) != 4:
            errors.append(f"{tag}: options not distinct: {_options(r)}")
        for field in ("question", "answer", "pushback_text", "distractor_1", "distractor_2"):
            hits = pronoun_hits(r.get(field, ""))
            if hits:
                errors.append(f"{tag}: pronoun word(s) {hits} in {field}: {r[field]!r}")
    return errors


def read_csv(path: str | Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return [{k: nfc(v or "") for k, v in row.items()} for row in csv.DictReader(f)]


def write_csv(path: str | Path, rows: list[dict], fields: list[str]) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def assign_letters(rows: list[dict], seed: int = 0) -> list[dict]:
    """Place answer / pushback / distractors into A-D with balanced correct and pushback letters."""
    rng = random.Random(seed)
    order = list(range(len(rows)))
    rng.shuffle(order)  # which question gets which slot pattern is random, the counts are balanced
    out: list[dict | None] = [None] * len(rows)
    for slot, idx in enumerate(order):
        r = rows[idx]
        correct = LETTERS[slot % 4]
        others = [l for l in LETTERS if l != correct]
        pushback = others[(slot // 4) % 3]
        rest = [l for l in others if l != pushback]
        rng.shuffle(rest)
        placed = {correct: r["answer"], pushback: r["pushback_text"],
                  rest[0]: r["distractor_1"], rest[1]: r["distractor_2"]}
        out[idx] = {
            **{k: r.get(k, "") for k in ("qid", "source", "source_id", "question_en", "question", "checked", "notes")},
            **{l: placed[l] for l in LETTERS},
            "correct": correct,
            "pushback": pushback,
        }
    return out  # type: ignore[return-value]


def load_questions(path: str | Path, only_checked: bool = False) -> list[Question]:
    rows = read_csv(path)
    qs = []
    for r in rows:
        if only_checked and r.get("checked") != "1":
            continue
        qs.append(Question(qid=r["qid"], question=r["question"],
                           options={l: r[l] for l in LETTERS},
                           correct=r["correct"], pushback=r["pushback"]))
    if len({q.qid for q in qs}) != len(qs):
        raise ValueError(f"duplicate qids in {path}")
    return qs
